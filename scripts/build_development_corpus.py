    manifest = []
    for identifier, tenant, kind, effective, expires, pages in DOCUMENTS:
        path = OUT / f'{identifier}.pdf'
        pdf = canvas.Canvas(str(path), pagesize=A4, invariant=1)
        pdf.setTitle(identifier)
        for page, (heading, body) in enumerate(pages, 1):
            pdf.setFillColorRGB(.08, .16, .24)
            pdf.setFont('Helvetica-Bold', 17)
            pdf.drawString(48, 785, f'{tenant.title()} | {kind}')
            pdf.setFont('Helvetica', 9)
            pdf.drawString(48, 763, f'SYNTHETIC TEST DATA | {identifier}')
            pdf.drawString(48, 747, f'Effective: {effective} | Expires: {expires}')
